#!/usr/bin/env node
// Compare the contracts and examples in this repository with the frozen
// design pack. Localized prose is compared structurally; everything else
// must match exactly.
//
// When the design pack is absent (CI, fresh clones) the copies are verified
// against contracts/contracts.lock.json instead. That lock is not trusted on
// its own: its pack id must match EXPECTED_PACK and the provenance anchors
// recorded in contracts/UPSTREAM.md must still agree with the lock, so a
// rewritten lock cannot quietly bless drifted contract bytes.
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const argv = process.argv.slice(2);
const packArg = argv.find((value) => value.startsWith("--pack="));
const updateLock = argv.includes("--update-lock");
const lockFile = join(repoRoot, "contracts", "contracts.lock.json");
const upstreamDoc = join(repoRoot, "contracts", "UPSTREAM.md");
const packRoot = resolve(
  packArg
    ? packArg.slice("--pack=".length)
    : process.env.CI_DIET_DESIGN_PACK ??
      join(repoRoot, "..", "..", "..", "..", "_design", "ci-diet", "v0.2.1", "ci-diet-design-v0.2.1")
);

// Provenance anchors. These duplicate contracts/UPSTREAM.md on purpose: the
// lock is regenerated by this same script, so the authority it carries has to
// be pinned somewhere that only a reviewed change can edit.
const EXPECTED_PACK = "ci-diet-design-v0.2.1";
const EXPECTED_ARCHIVE_SHA256 = "3b9e301fe772b7225f1a7e2625151e8129dbc5988fbd316a8d90c3b3e28409ce";

// Pointers whose string value is localized prose. Everything else is exact.
const LOCALIZED = new Map([
  ["contracts/coverage-policy.json", ["/levels/full", "/levels/subset", "/levels/degrade", "/levels/skip"]],
  ["examples/finding-evaluation.json", ["/reason"]],
  ["examples/partial-progress.json", ["/budget/wireRequestCount/reason"]]
]);

// Pointers added by this repository on purpose. The repository must have the
// pointer and the pack must not, so the extension shows up in review.
const EXTENDED = new Map([
  ["contracts/ci-diet.schema.json", ["/$defs/Finding/properties/message", "/$defs/Config/properties/billing"]],
  ["contracts/coverage-policy.json", ["/rules/CD006"]]
]);

// Enum values added by this repository on purpose, with the same rule: the
// repository copy must contain the value and the pack copy must not. The value
// is removed before the trees are compared, so every other member of the enum
// stays byte-for-byte identical to the pack.
const EXTENDED_VALUES = new Map([
  ["contracts/ci-diet.schema.json", [
    { pointer: "/$defs/AppliedChange/properties/state/enum", value: "REVERTING" },
    {"pointer":"/$defs/Config/properties/apply/properties/allowedRules/items/enum","value":"CD006"},
    {"pointer":"/$defs/Finding/properties/ruleId/enum","value":"CD006"},
    {"pointer":"/$defs/RuleResult/properties/ruleId/enum","value":"CD006"},
    {"pointer":"/$defs/ByteEdit/properties/ruleId/enum","value":"CD006"},
    {"pointer":"/$defs/PatchPayload/properties/ruleIds/items/enum","value":"CD006"},
    {"pointer":"/$defs/ReleaseScope/properties/enabledRules/items/enum","value":"CD006"},
    {"pointer":"/$defs/ReleaseScope/properties/patchVerifiedRules/items/enum","value":"CD006"}
  ]],
  ["examples/default-config.json", [{ pointer: "/apply/allowedRules", value: "CD006" }]]
]);

// Translated markdown: compare existence and parseability only.
const PROSE_ONLY = new Set(["examples/README.md"]);

// Files that exist only in this repository.
const REPO_ONLY = new Set(["contracts/UPSTREAM.md", "contracts/contracts.lock.json"]);

const errors = [];
const listFiles = (dir, prefix) => {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const rel = prefix + "/" + name;
    if (statSync(full).isDirectory()) out.push(...listFiles(full, rel));
    else out.push(rel);
  }
  return out.sort();
};

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

const listRepoArea = (area) => listFiles(join(repoRoot, area), area).filter((rel) => !REPO_ONLY.has(rel));

const readLock = () => {
  try {
    const lock = JSON.parse(readFileSync(lockFile, "utf8"));
    if (lock === null || typeof lock !== "object" || Array.isArray(lock)) {
      errors.push("contracts/contracts.lock.json: expected a JSON object");
      return {};
    }
    return lock;
  } catch (error) {
    errors.push("contracts/contracts.lock.json: cannot be read (" + error.message + ")");
    return {};
  }
};

// The lock may only carry the authority of the pack named here. A lock with a
// different pack id was either generated against another design revision or
// edited by hand; either way its hashes prove nothing about this repository.
const checkLockProvenance = (lock) => {
  if (lock.pack !== EXPECTED_PACK) {
    errors.push(
      'contracts/contracts.lock.json: pack "' + String(lock.pack) + '" is not "' + EXPECTED_PACK + '"'
    );
  }
  const files = lock.files;
  if (files === null || typeof files !== "object" || Array.isArray(files)) {
    errors.push("contracts/contracts.lock.json: files must be an object of sha256 digests");
    return;
  }
  for (const [rel, hash] of Object.entries(files)) {
    if (typeof hash !== "string" || !/^[0-9a-f]{64}$/.test(hash)) {
      errors.push("contracts/contracts.lock.json: " + rel + " has an invalid sha256");
    }
  }
};

// contracts/UPSTREAM.md records where the copies came from. Those anchors must
// still agree with the lock, otherwise the lock has outlived its provenance.
const checkUpstreamAnchors = (lock) => {
  let text;
  try {
    text = readFileSync(upstreamDoc, "utf8");
  } catch {
    errors.push("contracts/UPSTREAM.md: provenance document is missing");
    return;
  }
  if (!text.includes("`" + EXPECTED_PACK + "`")) {
    errors.push("contracts/UPSTREAM.md: pack is not " + EXPECTED_PACK);
  }
  const archive = /Archive sha256 \| `([0-9a-f]{64})`/.exec(text);
  if (archive === null) {
    errors.push("contracts/UPSTREAM.md: archive sha256 anchor is missing");
  } else if (archive[1] !== EXPECTED_ARCHIVE_SHA256) {
    errors.push("contracts/UPSTREAM.md: archive sha256 " + archive[1] + " is not " + EXPECTED_ARCHIVE_SHA256);
  }
  const files = lock.files ?? {};
  for (const line of text.split(/\r?\n/)) {
    const row = /^\| `([^`]+)` \| `([0-9a-f]{8})…` \| (same|differs) \|/.exec(line);
    if (row === null) continue;
    const [, rel, prefix, verdict] = row;
    const hash = files[rel];
    if (typeof hash !== "string") {
      errors.push("contracts/contracts.lock.json: " + rel + " is documented in contracts/UPSTREAM.md but missing from the lock");
      continue;
    }
    if (verdict === "same" && !hash.startsWith(prefix)) {
      errors.push(rel + ": contracts/UPSTREAM.md says the copy is unchanged but the lock hash does not start with " + prefix);
    }
    if (verdict === "differs" && hash.startsWith(prefix)) {
      errors.push(rel + ": contracts/UPSTREAM.md says the copy differs but the lock hash matches the upstream " + prefix);
    }
  }
};

const verifyAgainstLock = () => {
  const lock = readLock();
  const files = lock.files ?? {};
  const actual = [...listRepoArea("contracts"), ...listRepoArea("examples")];
  let compared = 0;
  for (const [rel, hash] of Object.entries(files)) {
    if (!actual.includes(rel)) {
      errors.push(rel + ": missing in this repository");
      continue;
    }
    compared += 1;
    if (sha256(readFileSync(join(repoRoot, ...rel.split("/")))) !== hash) {
      errors.push(rel + ": changed since contracts.lock.json was written");
    }
  }
  for (const rel of actual) {
    if (!(rel in files)) errors.push(rel + ": not recorded in contracts.lock.json");
  }
  return compared;
};

const collectAreaHashes = () => {
  const files = {};
  for (const area of ["contracts", "examples"]) {
    for (const rel of listRepoArea(area)) {
      files[rel] = sha256(readFileSync(join(repoRoot, ...rel.split("/"))));
    }
  }
  return files;
};

const dig = (rel, side) => {
  const base = side === "repo" ? repoRoot : packRoot;
  return readFileSync(join(base, ...rel.split("/")));
};

const dropPointer = (root, pointer) => {
  const parts = pointer.split("/").slice(1);
  let node = root;
  for (let i = 0; i < parts.length - 1; i += 1) {
    node = node?.[parts[i]];
    if (node === undefined || node === null) return false;
  }
  const last = parts[parts.length - 1];
  if (node === null || typeof node !== "object" || !(last in node)) return false;
  delete node[last];
  return true;
};

const dropEnumValue = (root, pointer, value) => {
  const parts = pointer.split("/").slice(1);
  let node = root;
  for (let i = 0; i < parts.length - 1; i += 1) {
    node = node?.[parts[i]];
    if (node === undefined || node === null) return false;
  }
  const last = parts[parts.length - 1];
  const list = node?.[last];
  if (!Array.isArray(list)) return false;
  const index = list.indexOf(value);
  if (index === -1) return false;
  list.splice(index, 1);
  return true;
};

const diff = (left, right, path, out) => {
  if (out.length >= 20) return;
  if (left === right) return;
  const isObject = (value) => value !== null && typeof value === "object";
  if (!isObject(left) || !isObject(right) || Array.isArray(left) !== Array.isArray(right)) {
    out.push(path + ": " + JSON.stringify(left) + " != " + JSON.stringify(right));
    return;
  }
  if (Array.isArray(left)) {
    if (left.length !== right.length) {
      out.push(path + ": array length " + left.length + " != " + right.length);
      return;
    }
    for (let i = 0; i < left.length; i += 1) diff(left[i], right[i], path + "/" + i, out);
    return;
  }
  for (const key of new Set([...Object.keys(left), ...Object.keys(right)])) {
    if (!(key in left) || !(key in right)) {
      out.push(path + "/" + key + ": missing on one side");
      continue;
    }
    diff(left[key], right[key], path + "/" + key, out);
  }
};

const compareTree = (area) => {
  const repoFiles = listFiles(join(repoRoot, area), area).filter((rel) => !REPO_ONLY.has(rel));
  const packFiles = listFiles(join(packRoot, area), area);
  let compared = 0;
  for (const rel of packFiles) {
    if (!repoFiles.includes(rel)) {
      errors.push(rel + ": missing in this repository");
      continue;
    }
  }
  for (const rel of repoFiles) {
    if (!packFiles.includes(rel)) {
      errors.push(rel + ": not present in the design pack");
      continue;
    }
    compared += 1;
    if (PROSE_ONLY.has(rel)) continue;
    const repoBytes = dig(rel, "repo");
    const packBytes = dig(rel, "pack");
    if (rel.endsWith(".json") && (EXTENDED.has(rel) || EXTENDED_VALUES.has(rel) || LOCALIZED.has(rel))) {
      const repoCopy = JSON.parse(repoBytes.toString("utf8"));
      const packCopy = JSON.parse(packBytes.toString("utf8"));
      for (const pointer of EXTENDED.get(rel) ?? []) {
        if (!dropPointer(repoCopy, pointer)) errors.push(rel + pointer + ": extended pointer missing in this repository");
        if (dropPointer(packCopy, pointer)) errors.push(rel + pointer + ": unexpectedly present in the design pack");
      }
      for (const { pointer, value } of EXTENDED_VALUES.get(rel) ?? []) {
        if (!dropEnumValue(repoCopy, pointer, value)) errors.push(rel + pointer + ": extended value " + value + " missing in this repository");
        if (dropEnumValue(packCopy, pointer, value)) errors.push(rel + pointer + ": value " + value + " unexpectedly present in the design pack");
      }
      for (const pointer of LOCALIZED.get(rel) ?? []) {
        if (!dropPointer(repoCopy, pointer)) errors.push(rel + pointer + ": localized pointer missing in this repository");
        if (!dropPointer(packCopy, pointer)) errors.push(rel + pointer + ": localized pointer missing in the design pack");
      }
      const drift = [];
      diff(repoCopy, packCopy, rel, drift);
      errors.push(...drift);
      continue;
    }
    if (!repoBytes.equals(packBytes)) {
      errors.push(rel + ": bytes changed; localize it explicitly or restore the pack copy");
    }
  }
  return compared;
};

const reportErrors = () => {
  console.error("contract drift: " + errors.length + " problem(s)");
  for (const line of errors) console.error("  " + line);
};

const packAvailable = (() => {
  try {
    return statSync(packRoot).isDirectory();
  } catch {
    return false;
  }
})();

if (updateLock) {
  // Regenerating the lock is only meaningful next to the frozen pack: the lock
  // exists to carry the pack's authority, and a lock written from the working
  // tree alone would just certify whatever bytes happen to be there.
  if (!packAvailable) {
    console.error("refusing to update contracts/contracts.lock.json: the design pack is not present");
    console.error("  looked for: " + packRoot);
    console.error("  pass --pack=<unpacked design pack> or set CI_DIET_DESIGN_PACK");
    process.exit(1);
  }
  compareTree("contracts");
  compareTree("examples");
  if (errors.length > 0) {
    reportErrors();
    process.exit(1);
  }
  const files = collectAreaHashes();
  writeFileSync(lockFile, JSON.stringify({ pack: EXPECTED_PACK, files }, null, 2) + "\n");
  const written = readLock();
  checkLockProvenance(written);
  checkUpstreamAnchors(written);
  const compared = verifyAgainstLock();
  if (errors.length > 0) {
    reportErrors();
    process.exit(1);
  }
  console.log("wrote and verified contracts/contracts.lock.json (" + compared + " files, " + EXPECTED_PACK + ")");
  process.exit(0);
}

const lock = readLock();
checkLockProvenance(lock);
checkUpstreamAnchors(lock);
const count = packAvailable ? compareTree("contracts") + compareTree("examples") : verifyAgainstLock();
if (errors.length > 0) {
  reportErrors();
  process.exitCode = 1;
} else {
  console.log(
    packAvailable
      ? "contracts match the frozen pack (" + count + " files, " + LOCALIZED.size + " localized files)"
      : "contracts match contracts.lock.json (" + count + " files, " + EXPECTED_PACK + "; design pack not present)"
  );
}
