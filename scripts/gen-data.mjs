#!/usr/bin/env node
// Generate frozen contract data modules from contracts/.
// Usage: node scripts/gen-data.mjs [--check]
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

async function readJson(name) {
  return JSON.parse(await readFile(path.join(root, "contracts", name), "utf8"));
}

const pricing = await readJson("pricing-2026-10-20.json");
const coverage = await readJson("coverage-policy.json");
const schema = await readJson("ci-diet.schema.json");
const defaultConfig = JSON.parse(await readFile(path.join(root, "examples", "default-config.json"), "utf8"));

const dataTarget = path.join(root, "src", "core", "data", "contracts.generated.ts");
const dataContent = [
  "// Generated by scripts/gen-data.mjs from contracts/. Do not edit by hand.",
  "// Regenerate with: node scripts/gen-data.mjs",
  "",
  "/** Frozen GitHub Actions list prices as published in contracts/pricing-2026-10-20.json. */",
  "export const PRICING_SNAPSHOT_JSON =",
  "  " + JSON.stringify(JSON.stringify(pricing)) + ";",
  "",
  "/** Machine-readable coverage policy from contracts/coverage-policy.json. */",
  "export const COVERAGE_POLICY_JSON =",
  "  " + JSON.stringify(JSON.stringify(coverage)) + ";",
  "",
  "/** Default configuration from examples/default-config.json. */",
  "export const DEFAULT_CONFIG_JSON =",
  "  " + JSON.stringify(JSON.stringify(defaultConfig)) + ";",
  "",
].join("\n");

const schemaTarget = path.join(root, "src", "core", "contracts", "schema-json.generated.ts");
const schemaContent = [
  "// Generated by scripts/gen-data.mjs from contracts/ci-diet.schema.json. Do not edit by hand.",
  "// Regenerate with: node scripts/gen-data.mjs",
  "",
  "export const CI_DIET_SCHEMA_JSON =",
  "  " + JSON.stringify(JSON.stringify(schema)) + ";",
  "",
].join("\n");

const targets = [
  { target: dataTarget, content: dataContent },
  { target: schemaTarget, content: schemaContent },
];

if (process.argv.includes("--check")) {
  let stale = 0;
  for (const { target, content } of targets) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== content) {
      console.error(path.relative(root, target) + " is stale; run: node scripts/gen-data.mjs");
      stale += 1;
    }
  }
  if (stale > 0) process.exit(1);
  console.log("generated contract data is current");
  process.exit(0);
}

for (const { target, content } of targets) {
  await writeFile(target, content, "utf8");
  console.log("wrote " + path.relative(root, target));
}
