export interface StyleDocument {
  readonly head: { appendChild(node: StyleElement): void };
  querySelector(selector: string): StyleNode | null;
  createElement(tag: string): StyleElement;
}

interface StyleNode {
  textContent: string;
  remove(): void;
}

interface StyleElement extends StyleNode {
  setAttribute(name: string, value: string): void;
}

declare const document: StyleDocument | undefined;

function currentDocument(): StyleDocument | undefined {
  return typeof document === "undefined" ? undefined : document;
}

/** Install the section stylesheet once; the returned cleanup removes our own tag. */
export function installStyles(doc: StyleDocument | undefined = currentDocument()): () => void {
  if (doc === undefined || doc.head === undefined) return () => {};
  const existing = doc.querySelector("style[" + STYLE_ATTRIBUTE + "]");
  if (existing !== null) {
    if (existing.textContent !== CSS_TEXT) existing.textContent = CSS_TEXT;
    return () => {};
  }
  const style = doc.createElement("style");
  style.setAttribute(STYLE_ATTRIBUTE, "");
  style.textContent = CSS_TEXT;
  doc.head.appendChild(style);
  return () => { style.remove(); };
}
